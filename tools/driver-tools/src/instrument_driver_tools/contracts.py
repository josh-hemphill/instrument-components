"""Generate closed typed contracts/views; this is main SDK tooling, not runtime reflection."""
from pathlib import Path
import json
import re


def pascal(text):
    return ''.join(part[:1].upper() + part[1:] for part in text.split('_'))


def generate_contracts(manifest: dict) -> dict[str, str]:
    if manifest.get('schemaVersion') != 1 or manifest.get('contractMajor') != 1: raise ValueError('Unknown contract manifest version')
    identifiers = [*manifest['classes'], *manifest['units']]
    for name, choices in manifest['enums'].items():
        identifiers += [name, *choices, *choices.values()]
        if any(k != v for k,v in choices.items()):raise ValueError('Enum semantics must match in Rust and C#')
    for op in manifest['operations']:
        identifiers += [op['id'], op['method'], op['kind'], op['unit']]
        identifiers += [p['name'] for p in op['parameters']]
        if op['result'] not in ['unit','quantity','boolean','count','samples','trace','identity']: raise ValueError('Unknown reply kind')
        if op['unit'] not in manifest['units']+['ConfiguredDmm','ConfiguredPower']: raise ValueError('Unknown result unit')
        if op['kind'] not in manifest['classes']+['Common']:raise ValueError('Unknown operation class')
        if len({p['name'] for p in op['parameters']}) != len(op['parameters']):raise ValueError('Duplicate parameter')
        for p in op['parameters']:
            if p['type'] not in ['number','optional_number','channel','count','boolean','symbol','waveform','power_unit','sense_mode']:raise ValueError('Unknown parameter type')
            if p['constraint'] not in ['finite','positive','nonnegative','percent','positive_integer','safe_symbol','enum','none','byte']:raise ValueError('Unknown parameter constraint')
        if 'setsUnit' in op and op['setsUnit'] not in manifest['units']+['PowerArgument']:raise ValueError('Unknown configured unit')
    if any(not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', n) for n in identifiers): raise ValueError('Unsafe contract identifier')
    if len({op['id'] for op in manifest['operations']}) != len(manifest['operations']): raise ValueError('Duplicate operation')
    ops = manifest['operations']
    rt = {'number':'f64', 'optional_number':'Option<f64>', 'channel':'u32', 'count':'u32', 'boolean':'bool', 'symbol':'String', 'waveform':'Waveform', 'power_unit':'PowerUnit', 'sense_mode':'SenseMode'}
    ct = {'number':'double', 'optional_number':'double?', 'channel':'uint', 'count':'uint', 'boolean':'bool', 'symbol':'string', 'waveform':'Waveform', 'power_unit':'PowerUnit', 'sense_mode':'SenseMode'}
    rr = {'unit':'()', 'quantity':'Quantity', 'boolean':'bool', 'count':'u32', 'samples':'Samples', 'trace':'Samples', 'identity':'DeviceIdentity'}
    cr = {'unit':'bool', 'quantity':'Quantity', 'boolean':'bool', 'count':'uint', 'samples':'Samples', 'trace':'Samples', 'identity':'DeviceIdentity'}
    rust = ['// @generated by instrument-driver contracts; edit spec/driver-operations.json.', 'use super::*;']
    cs = ['// <auto-generated by instrument-driver contracts />', '#nullable enable', 'using InstrumentComponents.Drivers;', 'namespace InstrumentComponents.Drivers.Catalog;', 'public enum CatalogOperation { '+', '.join(op['id'] for op in ops)+' }']
    rust += ['#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]', 'pub enum CatalogOperation { '+', '.join(op['id'] for op in ops)+' }']
    for name, choices in manifest['enums'].items():
        t = pascal(name)
        rust += ['#[derive(Debug, Clone, Copy, PartialEq, Eq)]', 'pub enum '+t+' { '+', '.join(choices)+' }']
        cs += ['public enum '+t+' { '+', '.join(choices)+' }']
    rust += ['#[derive(Debug, Clone, PartialEq)]', 'pub enum CatalogRequest {']
    for op in ops:
        fields=', '.join(p['name']+': '+rt[p['type']] for p in op['parameters'])
        rust += ['    '+op['id']+(' { '+fields+' }' if fields else '')+',']
    rust += ['}', 'impl CatalogRequest {', 'pub fn operation(&self) -> CatalogOperation { match self {']
    for op in ops:rust += ['Self::'+op['id']+(' { .. }' if op['parameters'] else '')+' => CatalogOperation::'+op['id']+',']
    rust += ['} }', 'pub fn arguments(&self) -> Vec<(&\'static str, Argument)> { match self {']
    for op in ops:
        names=', '.join(p['name'] for p in op['parameters']); vals=[]
        for p in op['parameters']:
            n=p['name'];t=p['type'];expr={'number':f'Argument::Number(*{n})','optional_number':f'Argument::OptionalNumber(*{n})','channel':f'Argument::Channel(*{n})','count':f'Argument::Count(*{n})','boolean':f'Argument::Boolean(*{n})','symbol':f'Argument::Symbol({n}.clone())'}.get(t,f'Argument::Symbol(format!("{{:?}}", {n}))')
            vals.append(f'("{n}", {expr})')
        rust += ['Self::'+op['id']+(' { '+names+' }' if names else '')+' => vec!['+', '.join(vals)+'],']
    rust += ['} }', 'pub fn validate(&self) -> Result<()> { match self {']
    for op in ops:
        names=', '.join(p['name'] for p in op['parameters']);checks=[]
        for p in op['parameters']:
            n=p['name'];t=p['type'];con=p['constraint']
            if t in ['number','optional_number']:checks.append(f'validate_number({"Some(*"+n+")" if t=="number" else "*"+n}, "{con}")?;')
            elif t=='count' and con=='byte':checks.append(f'if *{n} > 255 {{ return Err(invalid("byte value must be 0..255")); }}')
            elif t in ['channel','count']:checks.append(f'if *{n} == 0 {{ return Err(invalid("positive channel/count required")); }}')
            elif t=='symbol':checks.append(f'validate_symbol({n})?;')
            else:checks.append(f'let _ = {n};')
        rust += ['Self::'+op['id']+(' { '+names+' }' if names else '')+' => { '+' '.join(checks)+' },']
    rust += ['} Ok(()) }', 'pub fn result_kind(&self) -> (ReplyKind, Unit) { match self {']
    for op in ops:rust += ['Self::'+op['id']+(' { .. }' if op['parameters'] else '')+f' => (ReplyKind::{pascal(op["result"])}, Unit::{op["unit"]}),']
    rust += ['} }', 'pub fn configured_unit(&self) -> Option<Unit> { match self {']
    for op in ops:
        if 'setsUnit' not in op:continue
        if op['setsUnit']=='PowerArgument':rust += [f'Self::{op["id"]} {{ unit, .. }} => Some(match unit {{ PowerUnit::Watt => Unit::Watt, PowerUnit::Dbm => Unit::Dbm }}),']
        else:rust += [f'Self::{op["id"]} {{ .. }} => Some(Unit::{op["setsUnit"]}),']
    rust += ['_ => None, } }', '}']
    cs += ['public abstract record CatalogRequest {', 'public abstract CatalogOperation Operation { get; }', 'public abstract IReadOnlyDictionary<string, Argument> Arguments { get; }', 'public abstract (ReplyKind Kind, Unit Unit) Result { get; }', 'public virtual Unit? ConfiguredUnit => null;', 'private protected abstract void ValidateArguments();', 'public void Validate() => ValidateArguments();', '}']
    for op in ops:
        params=', '.join(ct[p['type']]+' '+pascal(p['name']) for p in op['parameters'])
        cs += [f'public sealed record {op["id"]}Request({params}) : CatalogRequest {{', f'public override CatalogOperation Operation => CatalogOperation.{op["id"]};', 'public override IReadOnlyDictionary<string, Argument> Arguments => new Dictionary<string, Argument> {']
        for p in op['parameters']:
            n=pascal(p['name']);t=p['type'];factory={'number':'Numeric','optional_number':'Optional','channel':'Channel','count':'Count','boolean':'Boolean','symbol':'Symbol'}.get(t,'Symbol')
            expr=n
            if t in manifest['enums']:expr=n+' switch { '+', '.join(ct[t]+'.'+k+' => "'+v+'"' for k,v in manifest['enums'][t].items())+', _ => throw ContractValidation.Invalid("Invalid enum") }'
            cs += [f'["{p["name"]}"] = Argument.{factory}({expr}),']
        cs += ['};', f'public override (ReplyKind Kind, Unit Unit) Result => (ReplyKind.{pascal(op["result"])}, Unit.{op["unit"]});']
        if 'setsUnit' in op:
            expr='Unit == PowerUnit.Watt ? Catalog.Unit.Watt : Catalog.Unit.Dbm' if op['setsUnit']=='PowerArgument' else 'Unit.'+op['setsUnit']
            # Qualification disambiguates the PowerMeter request's Unit parameter.
            expr=expr.replace('Catalog.Unit.', 'global::InstrumentComponents.Drivers.Catalog.Unit.')
            cs += ['public override Unit? ConfiguredUnit => '+expr+';']
        cs += ['private protected override void ValidateArguments() {']
        for p in op['parameters']:
            n=pascal(p['name']);t=p['type']
            if t in ['number','optional_number']:cs += [f'ContractValidation.Number({n}, "{p["constraint"]}");']
            elif t=='count' and p['constraint']=='byte':cs += [f'if ({n} > 255) throw ContractValidation.Invalid("Byte value must be 0..255");']
            elif t in ['channel','count']:cs += [f'if ({n} == 0) throw ContractValidation.Invalid("Positive channel/count required");']
            elif t=='symbol':cs += [f'ContractValidation.Symbol({n});']
            elif t in manifest['enums']:cs += [f'if (!Enum.IsDefined({n})) throw ContractValidation.Invalid("Invalid enum");']
        cs += ['}', '}']
    for kind in manifest['classes']:
        rust += [f'pub struct {kind}<\'a, E: ?Sized>(pub &\'a E);', f'impl<E: CatalogExecutor + ?Sized> {kind}<\'_, E> {{']
        selected=[op for op in ops if op['kind'] in [kind,'Common']]
        for op in selected:
            params=', '.join(p['name']+': '+rt[p['type']] for p in op['parameters']);names=', '.join(p['name'] for p in op['parameters']);variant='CatalogRequest::'+op['id']+(' { '+names+' }' if names else '')
            rust += [f'pub fn {op["method"]}(&self{", " if params else ""}{params}) -> Result<{rr[op["result"]]}> {{ self.0.invoke({variant})?.into_{op["result"]}() }}']
        rust += ['}']
        rust += ['#[cfg(feature="async")]', f'pub struct Async{kind}<\'a, E: ?Sized>(pub &\'a E);', '#[cfg(feature="async")]', f'impl<E: AsyncCatalogExecutor + ?Sized> Async{kind}<\'_, E> {{']
        for op in selected:
            params=', '.join(p['name']+': '+rt[p['type']] for p in op['parameters']);names=', '.join(p['name'] for p in op['parameters']);variant='CatalogRequest::'+op['id']+(' { '+names+' }' if names else '')
            rust += [f'pub async fn {op["method"]}(&self{", " if params else ""}{params}) -> Result<{rr[op["result"]]}> {{ self.0.invoke_async({variant}).await?.into_{op["result"]}() }}']
        rust += ['}']
        cs += [f'public sealed class {kind}(ICatalogExecutor executor) {{']
        for op in selected:
            params=', '.join(ct[p['type']]+' '+pascal(p['name']) for p in op['parameters']);args=', '.join(pascal(p['name']) for p in op['parameters']);ret='void' if op['result']=='unit' else cr[op['result']]
            cs += [f'public {ret} {op["id"].removeprefix(op["kind"])}({params}) => executor.Invoke(new {op["id"]}Request({args})).Into{pascal(op["result"])}();']
        cs += ['}',f'public sealed class Async{kind}(IAsyncCatalogExecutor executor) {{']
        for op in selected:
            params=', '.join(ct[p['type']]+' '+pascal(p['name']) for p in op['parameters']);args=', '.join(pascal(p['name']) for p in op['parameters']);ret='Task' if op['result']=='unit' else 'Task<'+cr[op['result']]+'>';body='return ' if op['result']!='unit' else ''
            cs += [f'public async {ret} {op["id"].removeprefix(op["kind"])}Async({params}{", " if params else ""}CancellationToken cancellationToken = default) {{ {body}(await executor.InvokeAsync(new {op["id"]}Request({args}), cancellationToken).ConfigureAwait(false)).Into{pascal(op["result"])}(); }}']
        cs += ['}']
    rust += ['impl CatalogOperation {', 'pub fn metadata(self) -> OperationMetadata { match self {']
    cs += ['public static class OperationDescriptions { public static OperationMetadata Describe(this CatalogOperation operation) => operation switch {']
    for op in ops:
        params = ', '.join('ParameterSpec { name: "'+p['name']+'", kind: ParameterKind::'+pascal(p['type'])+', constraint: \"'+p['constraint']+'\" }' for p in op['parameters'])
        rust += ['Self::'+op['id']+' => OperationMetadata { kind: "'+op['kind']+'", parameters: vec!['+params+'], result: ReplyKind::'+pascal(op['result'])+', unit: Unit::'+op['unit']+' },']
        params = ', '.join('new("'+p['name']+'", ParameterKind.'+pascal(p['type'])+', \"'+p['constraint']+'\")' for p in op['parameters'])
        cs += ['CatalogOperation.'+op['id']+' => new("'+op['kind']+'", ['+params+'], ReplyKind.'+pascal(op['result'])+', Unit.'+op['unit']+'),']
    rust += ['} } }']
    cs += ['_ => throw ContractValidation.Invalid("Unknown operation"), }; }']
    domains={'Boolean':['true','false'], **{pascal(k):list(v) for k,v in manifest['enums'].items()}}
    rust += ['impl ParameterKind { pub fn semantic_values(self) -> Option<&\'static [&\'static str]> { match self {']
    cs += ['public static class ParameterDomains { public static IReadOnlyList<string>? SemanticValues(this ParameterKind kind) => kind switch {']
    for kind,values in domains.items():
        literals=', '.join(json.dumps(v) for v in values)
        rust += ['Self::'+kind+' => Some(&['+literals+']),']
        cs += ['ParameterKind.'+kind+' => Array.AsReadOnly(new string[] { '+literals+' }),']
    rust += ['_ => None, } } }'];cs += ['_ => null, }; }']
    # C# enum members must be emitted as one declaration; Rust tags catalog operations.
    old=['MeasureVoltageDc','SetVoltage','ReadVoltage','OutputEnable','RemoteSense','Reset','Shutdown']
    cs_op='// <auto-generated by instrument-driver contracts />\nnamespace InstrumentComponents.Drivers;\npublic enum Operation { '+', '.join(old+['Catalog'+op['id'] for op in ops])+' }\n'
    rust += ['impl CatalogOperation { pub fn runtime_operation(self) -> Operation { Operation::Catalog(self) } }']
    cs += ['public static class CatalogOperations { public static Operation Runtime(this CatalogOperation op) => op switch {']
    cs += [f'CatalogOperation.{op["id"]} => Operation.Catalog{op["id"]},' for op in ops]
    cs += ['_ => throw ContractValidation.Invalid("Unknown operation"), }; }']
    cs_text = re.sub(r'(?<![\w:.])Unit\.', 'global::InstrumentComponents.Drivers.Catalog.Unit.', '\n'.join(cs)+'\n')
    return {'catalog_generated.rs':'\n'.join(rust)+'\n','CatalogGenerated.cs':cs_text,'OperationsGenerated.cs':cs_op}
