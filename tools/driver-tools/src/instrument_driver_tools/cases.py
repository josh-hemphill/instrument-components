"""Generate typed conformance cases; runtime consumers need no JSON reflection."""
import json
import math
from .contracts import pascal
from .profiles import catalogue, quoted, rust_strings


def emit_cases(data, module='generated_cases', namespace='GeneratedDrivers'):
    # Reuse identifier validation; generation does not use a source checkout.
    from .profiles import emit
    emit({'profiles': []}, module, namespace)
    if set(data) - {'schemaVersion','contractMajor','description','cases'} or data.get('schemaVersion') != 1 or data.get('contractMajor') != 1:
        raise ValueError('Unknown scenario schema/contract version/fields')
    metadata = {op['id']:op for op in catalogue()['operations']}
    errors = set('InvalidArgument DuplicateDriver IncompatibleContract DriverNotFound AmbiguousDriver UnsupportedOperation UnsupportedExecutionMode DriverContractViolation Transport Timeout Parse Device SessionNeedsRecovery SessionClosing SessionClosed Shutdown'.split())
    units = set(catalogue()['units'])
    for item in data['cases']:
        if 'expectedError' in item and item['expectedError'] not in errors: raise ValueError('Unknown expected error')
        for step in item['script']:
            if 'error' in step and step['error'] not in errors: raise ValueError('Unknown injected error')
        if 'expected' in item and item['expected'].get('status','Valid') not in ('Valid','Overload'): raise ValueError('Unknown measurement status')
        if 'expected' in item and 'unit' in item['expected'] and item['expected']['unit'] not in units: raise ValueError('Unknown quantity unit')
    rust = ['// @generated by instrument-driver generate-tests; edit shared scenario input.', f'pub mod {module} {{', 'use instrument_api::{catalog::*, ErrorKind, MeasurementStatus};', 'use instrument_testkit::{CatalogCase, ScriptStep};', 'pub fn cases() -> Vec<CatalogCase> { vec![']
    cs = ['// <auto-generated by instrument-driver generate-tests />','#nullable enable','using InstrumentComponents.Drivers;','using InstrumentComponents.Drivers.Catalog;', 'using SenseMode = InstrumentComponents.Drivers.Catalog.SenseMode;','using InstrumentComponents.TestKit;',f'namespace {namespace};','public static class GeneratedCases { public static IReadOnlyList<CatalogCase> Create() => new CatalogCase[] {']
    ids=set()
    def scalar(v):
        if isinstance(v,bool):return 'true' if v else 'false'
        if isinstance(v,(int,float)) and math.isfinite(v):return repr(float(v))
        raise ValueError('Invalid numeric scalar')
    for case in data['cases']:
        if set(case)-{'id','calls','script','expected','expectedError'} or not isinstance(case['id'],str) or case['id'] in ids:
            raise ValueError('Duplicate/invalid scenario')
        ids.add(case['id']);rust += ['CatalogCase { id: '+quoted(case['id'])+', calls: vec!['];cs += ['new CatalogCase('+quoted(case['id'])+', new CatalogRequest[] {']
        for call in case['calls']:
            if set(call) != {'operation','arguments'}:raise ValueError('Invalid call fields')
            op=metadata[call['operation']];args=call['arguments'];rargs=[];cargs=[]
            if set(args) != {p['name'] for p in op['parameters']}:raise ValueError('Call parameter mismatch')
            for p in op['parameters']:
                v=args[p['name']];typ=p['type']
                if typ=='optional_number':rv='None' if v is None else 'Some('+scalar(v)+')';cv='null' if v is None else scalar(v)
                elif typ=='number':rv=cv=scalar(v)
                elif typ=='channel':
                    if not isinstance(v,int) or isinstance(v,bool) or not 0<=v<=4294967295:raise ValueError('Invalid channel scalar')
                    rv=cv=str(v)
                elif typ=='boolean':
                    if not isinstance(v,bool):raise ValueError('Invalid boolean')
                    rv=cv='true' if v else 'false'
                elif typ=='symbol':
                    if not isinstance(v,str):raise ValueError('Invalid symbol')
                    rv=quoted(v)+'.into()';cv=quoted(v)
                else:
                    choices=catalogue()['enums'][typ]
                    if v not in choices:raise ValueError('Invalid enum choice')
                    rv=pascal(typ)+'::'+v;cv=pascal(typ)+'.'+v
                rargs.append(p['name']+': '+rv);cargs.append(cv)
            rust += ['CatalogRequest::'+op['id']+(' { '+', '.join(rargs)+' }' if rargs else '')+','];cs += ['new '+op['id']+'Request('+', '.join(cargs)+'),']
        rust += ['], script: vec!['];cs += ['}, new ScriptStep[] {']
        for step in case['script']:
            if set(step)-{'kind','message','response','error'}:raise ValueError('Unknown script field')
            kind=step['kind'];message=quoted(step.get('message',''));error=step.get('error');result='Err(instrument_api::DriverError::new(ErrorKind::'+error+', "injected script failure"))' if error else 'Ok(())'
            if kind=='write':
                rust += [('ScriptStep::WriteFailure('+message+'.into(), instrument_api::DriverError::new(ErrorKind::'+error+', \"injected\")),' if error else 'ScriptStep::Write('+message+'.into()),')]
            elif kind=='query':rust += ['ScriptStep::Query('+message+'.into(), '+('Err(instrument_api::DriverError::new(ErrorKind::'+error+', "injected"))' if error else 'Ok('+quoted(step['response'])+'.into())')+'),']
            elif kind in ['recover','close']:rust += ['ScriptStep::'+pascal(kind)+'('+result+'),']
            else:raise ValueError('Unknown script kind')
            cs += ['new ScriptStep('+quoted(kind)+', '+message+', '+quoted(step.get('response',''))+', '+('DriverErrorKind.'+error if error else 'null')+'),']
        rust += ['],'];cs += ['},']
        if 'expectedError' in case:
            if 'expected' in case:raise ValueError('Ambiguous outcome')
            rust += ['expected: None, expected_error: Some(ErrorKind::'+case['expectedError']+') },'];cs += ['null, DriverErrorKind.'+case['expectedError']+'),'];continue
        expected=case['expected'];kind=expected['kind']
        if kind=='unit':rv='CatalogReply::Unit';cv='new CatalogReply.Empty()'
        elif kind=='quantity':rv='CatalogReply::Quantity(Quantity { value: '+scalar(expected['value'])+', unit: Unit::'+expected['unit']+', status: MeasurementStatus::'+expected.get('status','Valid')+' })';cv='new CatalogReply.Numeric(new Quantity('+scalar(expected['value'])+', Unit.'+expected['unit']+', MeasurementStatus.'+expected.get('status','Valid')+'))'
        elif kind=='boolean':rv='CatalogReply::Boolean('+scalar(expected['value'])+')';cv='new CatalogReply.State('+scalar(expected['value'])+')'
        elif kind=='count':rv='CatalogReply::Count('+str(expected['value'])+')';cv='new CatalogReply.Count('+str(expected['value'])+')'
        elif kind in ['samples','trace']:
            arr=', '.join(scalar(v) for v in expected['values']);dt=expected.get('interval');rdt='Some('+scalar(dt)+')' if dt is not None else 'None';cdt=scalar(dt) if dt is not None else 'null'
            rv='CatalogReply::Samples(Samples { values: vec!['+arr+'], unit: Unit::'+expected['unit']+', sample_interval_s: '+rdt+' })';cv='new CatalogReply.Trace(new Samples(new double[] { '+arr+' }, Unit.'+expected['unit']+', '+cdt+'))'
        elif kind=='identity':
            rv='CatalogReply::Identity(DeviceIdentity { '+', '.join(n+': '+quoted(expected[n])+'.into()' for n in ['manufacturer','model','serial','revision'])+' })';cv='new CatalogReply.Identity(new InstrumentComponents.Drivers.Catalog.DeviceIdentity('+', '.join(quoted(expected[n]) for n in ['manufacturer','model','serial','revision'])+'))'
        else:raise ValueError('Unknown expected kind')
        rust += ['expected: Some('+rv+'), expected_error: None },'];cs += [cv+'),']
    rust += ['] }','}'];cs += ['}; }'];return {'cases.rs':rust_strings('\n'.join(rust)+'\n'),'GeneratedCases.cs':('\n'.join(cs)+'\n').replace('\u2028','\\u2028').replace('\u2029','\\u2029')}
