"""Explicit-input CLI usable from any working directory; emits no runtime JSON/reflection."""
import argparse
import json
from pathlib import Path
import subprocess
import sys
import tempfile
from . import VERSION
from .inventory import canonical, inventory


def read_json(path):
    raw=path.read_bytes()
    if len(raw)>8*1024*1024: raise ValueError('Manifest exceeds 8 MiB input limit')
    def pairs(items):
        result={}
        for key,value in items:
            if key in result: raise ValueError('Duplicate JSON property: '+key)
            result[key]=value
        return result
    def bad_constant(value): raise ValueError('Non-JSON numeric constant: '+value)
    return json.loads(raw,object_pairs_hook=pairs,parse_constant=bad_constant)


def write(path, content, check):
    if path.is_symlink():
        raise ValueError(f'Refusing symlink output: {path}')
    if check:
        if not path.is_file() or path.read_text() != content:
            raise ValueError(f'Generated output drift: {path}')
        return
    if path.exists() and not path.read_text().startswith(('// @generated', '// <auto-generated', '{')):
        raise ValueError(f'Refusing to overwrite non-generated file: {path}')
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode='w', dir=path.parent, encoding='utf-8', newline='\n', delete=False) as output:
        output.write(content); staged = Path(output.name)
    staged.replace(path)


def main(argv=None):
    parser = argparse.ArgumentParser(prog='instrument-driver')
    parser.add_argument('--version', action='version', version=VERSION)
    sub = parser.add_subparsers(dest='command', required=True)
    audit = sub.add_parser('inventory', help='Inventory an explicitly selected legacy checkout before extraction')
    audit.add_argument('--repository', type=Path, required=True)
    audit.add_argument('--output', type=Path, required=True)
    audit.add_argument('--check', action='store_true')
    gen = sub.add_parser('generate', help='Validate explicit profile input and generate static Rust/C# profiles')
    gen.add_argument('--input', type=Path, required=True)
    gen.add_argument('--schema', type=Path)
    gen.add_argument('--output-dir', type=Path, required=True)
    gen.add_argument('--module', default='generated_profiles')
    gen.add_argument('--namespace', default='GeneratedDrivers')
    gen.add_argument('--contract-major', type=int, required=True)
    gen.add_argument('--check', action='store_true')
    tests = sub.add_parser('generate-tests', help='Generate typed TestKit cases from an explicit shared scenario manifest')
    tests.add_argument('--input', type=Path, required=True)
    tests.add_argument('--output-dir', type=Path, required=True)
    tests.add_argument('--module', default='generated_cases')
    tests.add_argument('--namespace', default='GeneratedDrivers')
    tests.add_argument('--check', action='store_true')
    contracts = sub.add_parser('contracts', help='Regenerate SDK typed contracts from an explicit operation manifest')
    contracts.add_argument('--input', type=Path, required=True)
    contracts.add_argument('--rust-output', type=Path, required=True)
    contracts.add_argument('--dotnet-output', type=Path, required=True)
    contracts.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    try:
        if args.command == 'inventory':
            write(args.output, canonical(inventory(args.repository.resolve())), args.check)
        elif args.command in ('generate', 'generate-tests'):
            from .profiles import emit, validate
            data = read_json(args.input)
            if args.command == 'generate' and (args.contract_major != 1 or data.get('contractMajor') != args.contract_major):
                raise ValueError('Incompatible contract major')
            if args.command == 'generate':
                validate(data, args.schema)
                outputs = emit(data, args.module, args.namespace)
            else:
                from .cases import emit_cases
                outputs = emit_cases(data, args.module, args.namespace)
            if args.output_dir.is_symlink():
                raise ValueError('Refusing symlink output directory')
            # Validate all target paths before any file emission.
            for name in outputs:
                p = args.output_dir / name
                if p.is_symlink() or p.exists() and not p.read_text().startswith(('// @generated', '// <auto-generated')):
                    raise ValueError(f'Refusing non-generated output: {p}')
            for name, content in outputs.items():
                write(args.output_dir / name, content, args.check)
        else:
            from .contracts import generate_contracts
            data = read_json(args.input); outputs = generate_contracts(data)
            for name, content in outputs.items():
                if name.endswith('.rs'):
                    formatted = subprocess.run(['rustfmt', '--edition', '2021'], input=content, text=True, capture_output=True, check=True).stdout
                    write(args.rust_output / name, formatted, args.check)
                else:
                    write(args.dotnet_output / name, content, args.check)
    except Exception as error:
        parser.exit(1, f'{error}\n')
    return 0


if __name__ == '__main__':
    sys.exit(main())
