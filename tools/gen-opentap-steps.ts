import { mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from "node:fs";
/**
 * Generate explicit OpenTAP TestStep classes from spec/opentap-operations.json.
 */
const root = new URL("..", import.meta.url);
const manifestPath = new URL("spec/opentap-operations.json", root);
const sdkOperations = JSON.parse(readFileSync(new URL("spec/driver-operations.json",root),"utf8")).operations;
const outputDir = new URL("dotnet/src/InstrumentComponents.OpenTap/Steps/Generated/", root);

interface Parameter {
  name: string;
  displayName: string;
  type: string;
  enumType?: string;
  order: number;
  unit?: string;
  default?: unknown;
}

interface Invoke {
  operationId: string;
  method: string;
  returns?: string;
  args?: { parameter: string }[];
}

interface Operation {
  id: string;
  stepTypeName: string;
  implementation: string;
  kind: string;
  instrumentKind: string;
  instrumentType: string;
  accessor: string;
  displayName: string;
  displayGroups: string[];
  description?: string;
  parameters?: Parameter[];
  invoke?: Invoke;
  composite?: Invoke[];
  publish: { mode: string; name?: string; unit?: string; unitFrom?: string; supportsLimits?: boolean };
}

interface Manifest {
  operations: Operation[];
}

const INHERITED_LIMITS = new Set(["LimitLow", "LimitHigh"]);
const GENERATED_HEADER = "// <auto-generated by tools/gen-opentap-steps.ts />";

function csharpType(parameter: Parameter): string {
  return {
    string: "string",
    int: "int",
    uint: "uint",
    double: "double",
    bool: "bool",
    nullableDouble: "double?",
    enum: parameter.enumType ?? "string",
  }[parameter.type] ?? "object";
}

function defaultSuffix(parameter: Parameter): string {
  if (parameter.default === undefined) return "";
  if (parameter.type === "string") return ` = ${JSON.stringify(parameter.default)};`;
  if (parameter.type === "bool") return ` = ${parameter.default ? "true" : "false"};`;
  if (parameter.type === "enum") return ` = ${parameter.enumType}.${parameter.default};`;
  return ` = ${parameter.default};`;
}

function groupsLiteral(groups: string[]): string {
  return groups.map((group) => JSON.stringify(group)).join(", ");
}

function emittedParameters(operation: Operation): Parameter[] {
  return (operation.parameters ?? []).filter((parameter) => !INHERITED_LIMITS.has(parameter.name));
}

function emitProperty(parameter: Parameter): string {
  const unit = parameter.unit ? `\n    [Unit(${JSON.stringify(parameter.unit)})]` : "";
  return `    [Display(${JSON.stringify(parameter.displayName)}, Order: ${parameter.order})]${unit}
    public ${csharpType(parameter)} ${parameter.name} { get; set; }${defaultSuffix(parameter)}`;
}

function callArgs(operation: Operation): string {
  const args = operation.invoke?.args ?? [];
  if (args.length === 0) return "";
  return args.map((arg) => arg.parameter).join(", ");
}

function needsClassesUsing(operations: Operation[]): boolean {
  return operations.some((operation) =>
    (operation.parameters ?? []).some((parameter) => parameter.type === "enum")
  );
}

function emitConstructor(operation: Operation, parameters: Parameter[]): string {
  const rules: string[] = [];
  const constraints=new Map<string,string>();
  for(const invoke of operation.invoke ? [operation.invoke] : operation.composite ?? []) {
    const target=sdkOperations.find((o:{id:string})=>o.id===invoke.operationId);
    for(const [index,arg] of (invoke.args ?? []).entries()) {
      const constraint=target?.parameters[index]?.constraint;
      if(constraint && constraint!=="finite")constraints.set(arg.parameter,constraint);
    }
  }
  for (const parameter of parameters) {
    if (parameter.type === "uint") {
      rules.push(
        `        Rules.Add(() => ${parameter.name} >= 1, ${JSON.stringify(`${parameter.displayName} must be at least 1.`)}, nameof(${parameter.name}));`,
      );
    }
    if (parameter.type === "nullableDouble") {
      rules.push(`        Rules.Add(() => ${parameter.name} is null || double.IsFinite(${parameter.name}.Value), ${JSON.stringify(`${parameter.displayName} must be finite when set.`)}, nameof(${parameter.name}));`);
    }
    if (parameter.type === "double") {
      rules.push(
        `        Rules.Add(() => double.IsFinite(${parameter.name}), ${JSON.stringify(`${parameter.displayName} must be a finite number.`)}, nameof(${parameter.name}));`,
      );
    }
  }
  for(const parameter of parameters) {
    const constraint=constraints.get(parameter.name);
    if(!constraint || !["double","nullableDouble"].includes(parameter.type))continue;
    const value=parameter.type==="nullableDouble" ? `${parameter.name}.Value` : parameter.name;
    const condition=constraint==="positive" ? `${value} > 0` : constraint==="nonnegative" ? `${value} >= 0` : constraint==="percent" ? `${value} >= 0 && ${value} <= 100` : null;
    if(condition)rules.push(`        Rules.Add(() => ${parameter.type==="nullableDouble" ? `${parameter.name} is null || ` : ""}(${condition}), "${parameter.displayName} violates the operation's ${constraint} constraint.", nameof(${parameter.name}));`);
  }
  const names = new Set(parameters.map((parameter) => parameter.name));
  if (names.has("Channel1") && names.has("Channel2")) {
    rules.push(
      `        Rules.Add(() => Channel1 != Channel2, "Route endpoints must differ.", nameof(Channel1), nameof(Channel2));`,
    );
  }
  if (rules.length === 0) return "";
  return `    public ${operation.stepTypeName}()
    {
${rules.join("\n")}
    }

`;
}

function emitClass(
  operation: Operation,
  baseClass: string,
  runBody: string,
): string {
  const parameters = emittedParameters(operation);
  const properties = parameters.map(emitProperty).join("\n\n");
  const ctor = emitConstructor(operation, parameters);
  const header = `[Display(${JSON.stringify(operation.displayName)}, Groups: [${groupsLiteral(operation.displayGroups)}], Description: ${JSON.stringify(operation.description ?? "")})]`;
  const members = [properties, ctor.trimEnd() ? ctor.trimEnd() : "", `    public override void Run()\n    {\n${runBody}\n    }`]
    .filter((part) => part.length > 0)
    .join("\n\n");
  return `${header}
public sealed class ${operation.stepTypeName} : ${baseClass}
{
${members}
}`;
}

function emitScalarStep(operation: Operation): string {
  const resultName = operation.publish.name ?? operation.displayName;
  const unit = operation.publish.unitFrom ? `instrument.${operation.accessor}.${operation.publish.unitFrom}` : JSON.stringify(operation.publish.unit ?? "");
  const args = callArgs(operation);
  const invoke = `instrument.${operation.accessor}.${operation.invoke!.method}(${args})`;
  const valueExpr = operation.invoke!.returns === "bool" ? `${invoke} ? 1.0 : 0.0` : "quantity";
  const acquisition = operation.invoke!.returns === "bool" ? "" : `        var quantity = ${invoke};\n`;
  const physicalUnit = operation.invoke!.returns === "bool" ? unit : "PhaseIResults.UnitSymbol(quantity.Unit)";
  return emitClass(
    operation,
    `OptionalLimitStep<${operation.instrumentType}>`,
    `        if (!TryGetInstrument(out var instrument))
            return;

${acquisition}        PublishScalar(${JSON.stringify(resultName)}, ${valueExpr}, ${physicalUnit});`,
  );
}

function emitCommandStep(operation: Operation): string {
  const args = callArgs(operation);
  return emitClass(
    operation,
    `InstrumentBoundStep<${operation.instrumentType}>`,
    `        if (!TryGetInstrument(out var instrument))
            return;

        instrument.${operation.accessor}.${operation.invoke!.method}(${args});
        UpgradeVerdict(Verdict.Pass);`,
  );
}

function emitSampleTraceStep(operation: Operation): string {
  const args = callArgs(operation);
  const channel = operation.publish.name ?? "Trace";
  return emitClass(
    operation,
    `InstrumentBoundStep<${operation.instrumentType}>`,
    `        if (!TryGetInstrument(out var instrument))
            return;

        var samples = instrument.${operation.accessor}.${operation.invoke!.method}(${args});
        for (var i = 0; i < samples.Values.Count; i++)
            PhaseIResults.PublishSample(Results, ${JSON.stringify(channel)}, i, samples.Values[i]);
        UpgradeVerdict(samples.Values.All(double.IsFinite) ? Verdict.Pass : Verdict.Fail);`,
  );
}

function emitOperation(operation: Operation): string {
  if (operation.kind !== "invoke" || operation.invoke == null) {
    throw new Error(`${operation.id}: generated operations must be kind invoke`);
  }
  const returns = operation.invoke.returns;
  const mode = operation.publish.mode;
  if ((returns === "double" || returns === "bool") && mode === "scalar") {
    return emitScalarStep(operation);
  }
  if (returns === "void" && mode === "none") {
    return emitCommandStep(operation);
  }
  if (returns === "trace" && mode === "sample") {
    return emitSampleTraceStep(operation);
  }
  throw new Error(`${operation.id}: unsupported generated shape ${returns}/${mode}`);
}

function emitFile(kind: string, operations: Operation[]): string {
  const classesUsing = needsClassesUsing(operations) ? "using InstrumentComponents.Drivers.Catalog;\n" : "";
  const body = operations.map(emitOperation).join("\n\n");
  return `${GENERATED_HEADER}
${classesUsing}using OpenTap;

namespace InstrumentComponents.OpenTap;

${body}
`;
}

function main() {
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8")) as Manifest;
  const generated = manifest.operations
    .filter((operation) => operation.implementation === "generated")
    .sort((a, b) => a.stepTypeName.localeCompare(b.stepTypeName));
  if (generated.length === 0) {
    throw new Error("no generated operations in spec/opentap-operations.json");
  }

  mkdirSync(outputDir, { recursive: true });
  for (const stale of readdirSync(outputDir, { withFileTypes: true })) {
    if (stale.isFile() && stale.name.endsWith(".g.cs")) {
      unlinkSync(new URL(stale.name, outputDir));
    }
  }

  const byKind = new Map<string, Operation[]>();
  for (const operation of generated) {
    const list = byKind.get(operation.instrumentKind) ?? [];
    list.push(operation);
    byKind.set(operation.instrumentKind, list);
  }
  for (const [kind, operations] of [...byKind.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    writeFileSync(new URL(`${kind}Steps.g.cs`, outputDir), emitFile(kind, operations));
  }

  const names = generated.map((operation) => `        typeof(${operation.stepTypeName}),`).join("\n");
  const catalog = `${GENERATED_HEADER}
namespace InstrumentComponents.OpenTap;

public static class GeneratedOperationCatalog
{
    public static readonly Type[] StepTypes =
    [
${names}
    ];
}
`;
  writeFileSync(new URL("OperationCatalog.g.cs", outputDir), catalog);
}

main();
