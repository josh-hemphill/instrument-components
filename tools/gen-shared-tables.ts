function formatRustStrArray(name: string, commands: string[]): string {
  if (commands.length <= 4) {
    return `pub const ${name}: &[&str] = &[${commands.map((c) => `"${c}"`).join(", ")}];`;
  }
  const lines = commands.map((c) => `    "${c}",`).join("\n");
  return `pub const ${name}: &[&str] = &[\n${lines}\n];`;
}

function formatCsStrArray(name: string, commands: string[]): string {
  if (commands.length <= 4) {
    return `    internal static readonly string[] ${name} =\n        [${commands.map((c) => `"${c}"`).join(", ")}];`;
  }
  return `    internal static readonly string[] ${name} =\n        [${commands.map((c) => `"${c}"`).join(", ")}];`;
}

